function updateAlternateLinks(page) {
  document.head.querySelectorAll('link[data-alt-lang]').forEach((node) => node.remove());
  languages.forEach((lang) => {
    const link = document.createElement("link");
    link.rel = "alternate";
    link.hreflang = lang;
    link.href = `${window.location.origin}${pagePath(lang, page)}`;
    link.dataset.altLang = lang;
    document.head.appendChild(link);
  });
  const fallback = document.createElement("link");
  fallback.rel = "alternate";
  fallback.hreflang = "x-default";
  fallback.href = `${window.location.origin}${pagePath("en", page)}`;
  fallback.dataset.altLang = "x-default";
  document.head.appendChild(fallback);
}

