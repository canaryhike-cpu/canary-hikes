function mergeContentOverrides(target, source) {
  Object.entries(source).forEach(([key, value]) => {
    if (value && typeof value === "object" && !Array.isArray(value)) {
      target[key] = target[key] || {};
      mergeContentOverrides(target[key], value);
      return;
    }
    target[key] = value;
  });
}

