function initTeideDiagramMotion() {
  const diagram = document.querySelector('.teide-diagram');
  if (!diagram) return;
  const back = diagram.querySelector('.parallax-back');
  const mid = diagram.querySelector('.parallax-mid');
  const reduceMotion = window.matchMedia('(prefers-reduced-motion: reduce)').matches;

  if (!diagram.dataset.revealBound) {
    const observer = new IntersectionObserver((entries) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) diagram.classList.add('is-visible');
      });
    }, { threshold: 0.3 });
    observer.observe(diagram);
    diagram.dataset.revealBound = '1';
  }

  if (!reduceMotion && !diagram.dataset.scrollBound) {
    const updateProgress = () => {
      const rect = diagram.getBoundingClientRect();
      const start = window.innerHeight * 0.9;
      const end = -rect.height * 0.3;
      const progress = Math.min(1, Math.max(0, (start - rect.top) / (start - end)));
      diagram.style.setProperty('--scene-progress', progress.toFixed(3));
    };
    updateProgress();
    window.addEventListener('scroll', updateProgress, { passive: true });
    window.addEventListener('resize', updateProgress);
    diagram.dataset.scrollBound = '1';
  }

  if (!reduceMotion && !diagram.dataset.parallaxBound) {
    diagram.addEventListener('pointermove', (event) => {
      const rect = diagram.getBoundingClientRect();
      const dx = (event.clientX - rect.left) / rect.width - 0.5;
      const dy = (event.clientY - rect.top) / rect.height - 0.5;
      if (back) back.style.transform = `translate(${dx * 12}px, ${dy * 10}px)`;
      if (mid) mid.style.transform = `translate(${dx * 18}px, ${dy * 14}px)`;
    });
    diagram.addEventListener('pointerleave', () => {
      if (back) back.style.transform = '';
      if (mid) mid.style.transform = '';
    });
    diagram.dataset.parallaxBound = '1';
  }
}
function renderTeide(lang) {
  const main = document.querySelector("main");
  if (main.classList.contains("shop-page")) {
    main.className = "";
    main.innerHTML = teideMarkup;
  }
  document.querySelectorAll("[data-i18n]").forEach((node) => {
    node.textContent = valueFor(node.dataset.i18n, lang);
  });
  document.querySelectorAll("[data-i18n-alt]").forEach((node) => {
    node.alt = valueFor(node.dataset.i18nAlt, lang);
  });
  document.querySelectorAll("[data-i18n-svg]").forEach((node) => {
    node.textContent = valueFor(node.dataset.i18nSvg, lang);
  });
  renderList(lists.cable, content[lang].cable.list);
  renderGear(content[lang].gear.groups);
  renderTips(content[lang].tips.items);
  initTeideDiagramMotion();
}

function updateChrome(lang, page) {
  document.querySelector(".brand").href = pagePath(lang, "teide");
  document.querySelectorAll("[data-page-link]").forEach((link) => {
    const targetPage = link.dataset.pageLink;
    link.href = pagePath(lang, targetPage);
    link.classList.toggle("active", targetPage === page);
  });
  document.querySelectorAll("[data-shop-link]").forEach((link) => {
    link.href = pagePath(lang, link.dataset.shopLink);
  });
  document.querySelectorAll("[data-lang]").forEach((link) => {
    const targetLang = link.dataset.lang;
    link.classList.toggle("active", targetLang === lang);
    link.href = pagePath(targetLang, page);
  });
}

function setLanguage(lang, page = route.page) {
  if (!content[lang]) lang = "en";
  route.lang = lang;
  route.page = page;
  document.documentElement.lang = lang;
  setMeta(lang, page);
  updateAlternateLinks(page);
  updateChrome(lang, page);
  if (page === "teide") {
    renderTeide(lang);
  } else {
    document.querySelectorAll("header [data-i18n]").forEach((node) => {
      node.textContent = valueFor(node.dataset.i18n, lang);
    });
    renderShop(lang, page);
  }
  localStorage.setItem("teide-lang", lang);
}

document.querySelectorAll("[data-lang]").forEach((button) => {
  button.addEventListener("click", (event) => {
    if (window.location.pathname === "/" || window.location.search) {
      event.preventDefault();
      setLanguage(button.dataset.lang, route.page);
      window.history.replaceState({}, "", pagePath(button.dataset.lang, route.page));
    }
  });
});

setLanguage(route.lang || localStorage.getItem("teide-lang") || "en", route.page);
