function setMeta(lang, page) {
  const seo = seoFor(lang, page);
  const pageUrl = `${window.location.origin}${pagePath(lang, page)}`;
  document.title = seo.title;
  ensureMeta('meta[name="description"]', () => {
    const node = document.createElement("meta");
    node.name = "description";
    return node;
  }).content = seo.description;
  ensureMeta('meta[property="og:title"]', () => {
    const node = document.createElement("meta");
    node.setAttribute("property", "og:title");
    return node;
  }).content = seo.ogTitle;
  ensureMeta('meta[property="og:description"]', () => {
    const node = document.createElement("meta");
    node.setAttribute("property", "og:description");
    return node;
  }).content = seo.ogDescription;
  ensureMeta('meta[property="og:url"]', () => {
    const node = document.createElement("meta");
    node.setAttribute("property", "og:url");
    return node;
  }).content = pageUrl;
  ensureMeta('link[rel="canonical"]', () => {
    const node = document.createElement("link");
    node.rel = "canonical";
    return node;
  }).href = pageUrl;
}

function updateAlternateLinks(page) {
  document.head.querySelectorAll('link[data-alt-lang]').forEach((node) => node.remove());
  languages.forEach((lang) => {
    const link = document.createElement("link");
    link.rel = "alternate";
    link.hreflang = lang;
    link.href = `${window.location.origin}${pagePath(lang, page)}`;
    link.dataset.altLang = lang;
    document.head.appendChild(link);
  });
  const fallback = document.createElement("link");
  fallback.rel = "alternate";
  fallback.hreflang = "x-default";
  fallback.href = `${window.location.origin}${pagePath("en", page)}`;
  fallback.dataset.altLang = "x-default";
  document.head.appendChild(fallback);
}

